#ifndef DYNAMIC_LINOMETER_PARAMETER_H
#define DYNAMIC_LINOMETER_PARAMETER_H

#include "stm32l4xx_hal.h"
#include <stdint.h>

/*
*********************************************************************************************************
*                                          宏定义
*********************************************************************************************************
*/

#define PARAM_MCU_UID_WORDS       3     // MCU 96位唯一标识 = 3个32位字(UID_BASE=0x1FFF7590)
#define PARAM_MCU_UID_REG_NUM     6     // UID映射成的Modbus保持寄存器个数(96位/16位=6, 起始地址3000)

/*
*********************************************************************************************************
*                                          类型定义
*********************************************************************************************************
*/

typedef struct
{
    uint32_t MCU_UUID[PARAM_MCU_UID_WORDS];   // MCU唯一标识(HAL_GetUIDw0/w1/w2读取, 0x1FFF7590起)
    uint16_t UidReg[PARAM_MCU_UID_REG_NUM];   // UID的Modbus寄存器映像(3000~3005, 只读)
    uint32_t PICISN;                          // 预留

} DYNAMICLINOMETER_PARAM;

/*
*********************************************************************************************************
*                                          外部变量声明
*********************************************************************************************************
*/

extern DYNAMICLINOMETER_PARAM DynamicLinometerParam;   // 设备参数(含MCU唯一标识)

/*
*********************************************************************************************************
*                                          函数声明
*********************************************************************************************************
*/

void DynamicLinometerSNInit(void);              // 参数初始化(读取MCU唯一标识并生成寄存器映像)

#endif
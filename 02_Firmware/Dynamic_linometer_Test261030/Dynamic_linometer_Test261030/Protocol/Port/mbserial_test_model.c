#include "mbserial_defs.h"
#include <string.h>

INT16U MBValue[125];

/*
*********************************************************************************************************
* 描述   ：设置Modbus值
* 参数   ：value - Modbus值
*          num   - 数量
* 返回值 ：无
*********************************************************************************************************
*/

void MBSerialSlaveValueSet(INT16U *value, INT16U num)
{
	memcpy(MBValue, value, num * 2);
}

/*
*********************************************************************************************************
* 描述   ：获取Modbus值
* 参数   ：value - Modbus值
*          num   - 数量
* 返回值 ：无
*********************************************************************************************************
*/

void MBSerialSlaveValueGet(INT16U *value, INT16U num)
{
	memcpy(value, MBValue, num * 2);
}
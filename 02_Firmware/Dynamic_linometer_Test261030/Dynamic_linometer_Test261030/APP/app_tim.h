#ifndef APP_TIM_H
#define APP_TIM_H

#include "stm32l4xx_hal.h"

/*
*********************************************************************************************************
*                                          宏定义
*********************************************************************************************************
*/

#define TIM_TICK_FREQ_HZ           999            // 定时节拍频率(Hz)：取1.2倍ASM330轴输出速率(833Hz)
                                                  // 保证一拍内最多出现1个新样本；ODR变更时同步改此值(约1.2倍ODR)

/*
*********************************************************************************************************
*                                          外部变量声明
*********************************************************************************************************
*/

extern volatile uint32_t App_TimUpdateCnt;         // 定时节拍计数(每拍+1)
extern volatile uint8_t  App_TimTickFlag;          // 定时节拍标志(中断置1，主循环取走后清0)

/*
*********************************************************************************************************
*                                          函数声明
*********************************************************************************************************
*/

HAL_StatusTypeDef App_TimInit(void);               // 定时器初始化(节拍999Hz，为主循环直读提供节拍标志)
void              App_TimSetFreq(uint32_t hz);     // 重新设定节拍频率(Hz)，运行期ODR变更时调用
void              App_TimUpdateHandle(void);       // 定时更新处理(置节拍标志；模拟数据模式下生成模拟样本)

#endif
